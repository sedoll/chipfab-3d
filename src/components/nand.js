const B = (a) => G('blk', a);
const N = 10, T = 0.16, Y0 = 0.5, YT = Y0 + N * 2 * T;          // 쌍 수, 층 두께, 적층 시작/끝 높이
const SX = [-3.6, 4.6], SZ = [-3.2, 3.2];
const CX = [-2.2, -0.6, 1.0], CZ = [-1.8, 0, 1.8], RH = 0.42;   // 채널 위치/반지름
const chans = CX.flatMap((x, i) => CZ.map((z, j) => [x, z, i, j]));
const holes = chans.map(([x, z]) => [x, z, RH]);
const lo = (k) => Y0 + k * 2 * T;                               // k번째 쌍의 아래 높이
const x1 = (k) => 2.4 + ((N - 1 - k) * 2.2) / (N - 1);          // 계단: 아래층일수록 길게
const C1 = [[10.5, 7, 11.5], [0.5, 0.6, 0]], C2 = [[13, 5.5, 12], [0.6, 1.9, 0]];

const block = B([box('sub', [-3.8, 4.8], [-1.2, 0], [-3.4, 3.4], 'si')]);

// 적층 레이어: 옵션에 따라 평판/구멍 뚫린 판/계단 길이
const layers = (kind, mat, { holes: h = [], stair = false, o = 1, dl = 0 } = {}) =>
  R(N, (k) => {
    const [a, b] = kind === 'ox' ? [lo(k), lo(k) + T] : [lo(k) + T, lo(k) + 2 * T];
    const xr = [SX[0], stair ? x1(k) : SX[1]];
    const id = `${kind}.${k}`;
    return h.length || stair
      ? slab(id, xr, [a, b], SZ, h, mat, { o, dl, n: kind === 'ox' ? '산화막 (SiO₂)' : kind === 'w' ? '텅스텐 게이트 (워드라인)' : '질화막 (Si₃N₄)' })
      : box(id, xr, [a, b], SZ, mat, { o, dl, n: kind === 'ox' ? '산화막 (SiO₂)' : '질화막 (Si₃N₄)' });
  });

